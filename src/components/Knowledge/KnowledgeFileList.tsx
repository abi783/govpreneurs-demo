import { FileText, FileImage, FileArchive, FileCheck2, X } from "lucide-react";
import {
  CONNECTOR_META,
  removeFile,
  type KnowledgeSource,
} from "../../lib/knowledgeBase";

function fileIcon(mime: string) {
  if (mime === "image") return FileImage;
  if (mime === "zip") return FileArchive;
  return FileText;
}

function sourceChip(file: KnowledgeSource) {
  if (file.kind === "upload") return { label: "Uploaded", tone: "neutral" };
  if (file.kind === "generated") return { label: "Generated by Ava", tone: "ava" };
  return { label: CONNECTOR_META[file.kind].label, tone: "connector" };
}

function formatSize(kb: number): string {
  if (kb < 1024) return `${kb} KB`;
  return `${(kb / 1024).toFixed(1)} MB`;
}

function formatDate(iso: string): string {
  const d = new Date(iso);
  return d.toLocaleDateString(undefined, { month: "short", day: "numeric" });
}

export function KnowledgeFileList({ files }: { files: KnowledgeSource[] }) {
  if (files.length === 0) {
    return (
      <div className="kn-empty">
        No files yet. Connect a source above or attach files to get started.
      </div>
    );
  }

  return (
    <ul className="kn-file-list">
      {files.map((f) => {
        const Icon = f.kind === "generated" ? FileCheck2 : fileIcon(f.mime);
        const chip = sourceChip(f);
        return (
          <li key={f.id} id={`kn-file-${f.id}`} className="kn-file-row">
            <span className="kn-file-icon">
              <Icon size={16} />
            </span>
            <div className="kn-file-main">
              <div className="kn-file-name">{f.name}</div>
              <div className="kn-file-meta">
                <span className={`kn-chip kn-chip--${chip.tone}`}>{chip.label}</span>
                <span className="kn-file-dot">·</span>
                <span>{formatSize(f.sizeKB)}</span>
                <span className="kn-file-dot">·</span>
                <span>added {formatDate(f.addedAt)}</span>
              </div>
            </div>
            <button
              type="button"
              className="kn-file-remove"
              onClick={() => removeFile(f.id)}
              aria-label={`Remove ${f.name}`}
            >
              <X size={14} />
            </button>
          </li>
        );
      })}
    </ul>
  );
}
