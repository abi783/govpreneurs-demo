import { Link, useNavigate } from "@tanstack/react-router";
import { Download, PenLine } from "lucide-react";
import { ProfileTabSection } from "../ProfileTabSection";
import { FieldRow } from "../FieldRow";
import { useEditMode } from "../BusinessProfileMode";
import { markCapStatementUploaded, useCapStatementUploaded } from "../../../lib/capStatementState";
import { downloadCapStatement } from "../../../demo/profile/downloads";
import { fmtMoneyShort, fmtShort } from "../../../demo/profile/dates";
import { summarize, usePastPerformance } from "../../../demo/profile/pastPerformance";

// DEMO: the fields come from the story (src/demo/profile/fields.tsx). Two rows are
// built here because they come from other pages: the capability statement on file,
// and the past-performance summary.
export function CapabilitiesTab() {
  const cap = useCapStatementUploaded();
  const editMode = useEditMode();
  const pp = usePastPerformance();
  const navigate = useNavigate();
  const sum = summarize(pp);
  const savedDate = cap.savedAt ? fmtShort(cap.savedAt) : null;

  const capStmtRow = cap.uploaded ? (
    <div className="bp-capstmt-row" key="capability-statement">
      <FieldRow
        tier="T1"
        label="Capability Statement"
        state="attested"
        value={
          <span>
            {cap.origin === "ava" ? "Generated by Ava" : "Uploaded"}
            {savedDate ? ` on ${savedDate}` : ""} · saved to your knowledge base
          </span>
        }
        source={cap.fileName}
        whyItMatters="Federal contracting officers ask for this on first contact. Hunter and Grant can now cite it."
        editType="file"
        editValue=""
        onSave={(name) => markCapStatementUploaded(String(name))}
      />
      {editMode && (
        <div className="bp-capstmt-actions">
          <button type="button" className="bp-capstmt-build" onClick={() => void downloadCapStatement()}>
            <Download size={13} /> Download my capability statement
          </button>
          <Link to="/cap-statement/builder" className="bp-capstmt-dfy">
            Update it with Ava
          </Link>
        </div>
      )}
    </div>
  ) : (
    <div className="bp-capstmt-row" key="capability-statement">
      <FieldRow
        tier="T1"
        label="Capability Statement"
        state="missing"
        helperMicrocopy="A one-page PDF federal buyers expect. Without it, you're harder to take seriously even with everything else in place."
        whyItMatters="Federal contracting officers ask for this on first contact. Hunter flags this gap on every match."
        editType="file"
        onSave={(name) => markCapStatementUploaded(String(name))}
      />
      <div className="bp-capstmt-actions">
        <Link to="/cap-statement/builder" className="bp-capstmt-build">
          <PenLine size={13} /> Build my capability statement with Ava
        </Link>
        <Link to="/cap-statement/builder" className="bp-capstmt-dfy">
          Want us to build it for you?
        </Link>
      </div>
    </div>
  );

  const ppRow = (
    <FieldRow
      key="past-performance"
      tier="T2"
      label="Past Performance"
      state="attested"
      value={
        <span>
          {pp.length} {pp.length === 1 ? "entry" : "entries"} · Total {fmtMoneyShort(sum.total)} · {sum.federal} federal, {sum.local} local, {sum.commercial} commercial{" "}
          <Link to="/business-profile" search={{ tab: "past-performance" }} className="bp-inline-link">
            View all →
          </Link>
        </span>
      }
      source="From your past performance entries"
      onEdit={() => navigate({ to: "/business-profile", search: { tab: "past-performance" } })}
    />
  );

  return (
    <ProfileTabSection
      tab="capabilities"
      unlocks="This section unlocks: better Hunter matches and Grant's deeper bid memos"
      extra={{ T1: [capStmtRow], T2: [ppRow] }}
    />
  );
}
